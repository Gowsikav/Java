class Printer {

    static void display(byte b) {
        System.out.println("Byte: " + b);
    }

    static void display(short s) {
        System.out.println("Short: " + s);
    }

    static void display(int i) {
        System.out.println("Int: " + i);
    }

    static void display(long l) {
        System.out.println("Long: " + l);
    }

    static void display(float f) {
        System.out.println("Float: " + f);
    }

    static void display(double d) {
        System.out.println("Double: " + d);
    }

    static void display(char c) {
        System.out.println("Char: " + c);
    }

    static void display(boolean b) {
        System.out.println("Boolean: " + b);
    }

    static void display(String str) {
        System.out.println("String: " + str);
    }

    static void display(int num1,int num2) {  
        System.out.println("Addition: "+(num1+num2));
    }
}