class ArrayLength
{
	public static void main(String[] args) {
		
		String [] fruitName={"Apple","Mango","Grapes"};
		double[] price={23.946,784.2749,299.67,89.5,2398.674};
		char alpha[]={'e','a','i','o','u'};
		int []mark={39,89,90,65,94,76,60};
		System.out.println("String length: "+fruitName.length);
		System.out.println("Double length: "+price.length);
		System.out.println("Character length: "+alpha.length);
		System.out.println("Integer length: "+mark.length);

	}
}